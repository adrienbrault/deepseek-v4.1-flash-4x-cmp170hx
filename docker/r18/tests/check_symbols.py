#!/usr/bin/env python3
"""Check vLLM source imports and module attributes without importing vLLM.

The input is a source checkout root (the parent of vllm/). Paths after the
root are relative to it. With no paths, check the core series' paths.
With --overlays, also check the overlay series on the assembled packages.
Native extensions and external dependencies require a runtime. Generated
version exports are reported separately.
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from functools import cache
from pathlib import Path

# Version is generated by the wheel build. Native operator references within
# Python code go through torch.ops and are outside this source-only proof.
GENERATED_EXPORTS = {"vllm._version": {"__version__", "__version_tuple__"}}


def is_internal(name: str) -> bool:
    return name.partition(".")[0] in {"vllm", "vllm_exl3"}


def targets(node: ast.AST):
    if isinstance(node, ast.Name):
        yield node.id
    elif isinstance(node, (ast.List, ast.Tuple)):
        for child in node.elts:
            yield from targets(child)


def dotted(node: ast.AST) -> tuple[str, ...]:
    if isinstance(node, ast.Name):
        return (node.id,)
    if isinstance(node, ast.Attribute) and (parent := dotted(node.value)):
        return (*parent, node.attr)
    return ()


def import_base(node: ast.ImportFrom, package: str) -> str:
    if not node.level:
        return node.module or ""
    parts = package.split(".")
    if node.level > len(parts):
        return ""
    base = ".".join(parts[: len(parts) + 1 - node.level])
    return f"{base}.{node.module}" if node.module else base


class Bindings(ast.NodeVisitor):
    """Collect names declared in one lexical scope, including branch bodies."""

    def __init__(self, package: str):
        self.package = package
        self.names: dict[str, set[tuple[str, ...]]] = {}
        self.lazy: dict[str, tuple[str, ...]] = {}
        self.star: set[str] = set()

    def add(self, name: str, origin: tuple[str, ...] = ()) -> None:
        self.names.setdefault(name, set()).add(origin)

    def visit_Import(self, node: ast.Import) -> None:
        for entry in node.names:
            top = entry.name.split(".")[0]
            self.add(entry.asname or top, (entry.name if entry.asname else top,))

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        base = import_base(node, self.package)
        for entry in node.names:
            if entry.name == "*":
                if is_internal(base):
                    self.star.add(base)
            else:
                self.add(entry.asname or entry.name, (base, entry.name))

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        self.add(node.name)

    visit_AsyncFunctionDef = visit_ClassDef = visit_FunctionDef

    def visit_Assign(self, node: ast.Assign) -> None:
        for target in node.targets:
            for name in targets(target):
                self.add(name)
                if name in {"MODULE_ATTRS", "environment_variables"}:
                    self.capture_lazy(node.value, name)
        self.visit(node.value)

    def visit_AnnAssign(self, node: ast.AnnAssign) -> None:
        for name in targets(node.target):
            self.add(name)
            if name in {"MODULE_ATTRS", "environment_variables"} and node.value:
                self.capture_lazy(node.value, name)
        if node.value:
            self.visit(node.value)

    def visit_Name(self, node: ast.Name) -> None:
        if isinstance(node.ctx, ast.Store):
            self.add(node.id)

    def capture_lazy(self, node: ast.AST, mapping: str) -> None:
        if not isinstance(node, ast.Dict):
            return
        for key, value in zip(node.keys, node.values):
            if not isinstance(key, ast.Constant) or not isinstance(key.value, str):
                continue
            origin = ()
            if mapping == "MODULE_ATTRS" and isinstance(value, ast.Constant):
                if isinstance(value.value, str) and ":" in value.value:
                    parts = value.value.split(":", 1)
                    if parts[0].startswith("."):
                        parts[0] = self.package + parts[0]
                    origin = tuple(parts)
            self.lazy[key.value] = origin


class SourceIndex:
    def __init__(self, root: Path):
        self.root = root
        self.generated_refs: set[str] = set()

    @cache
    def path(self, name: str) -> Path | None:
        rel = self.root.joinpath(*name.split("."))
        for file in (rel / "__init__.py", rel.with_suffix(".py")):
            if file.is_file():
                return file
        return rel if rel.is_dir() else None

    def module(self, name: str) -> bool:
        if name in GENERATED_EXPORTS and self.path(name) is None:
            self.generated_refs.add(name)
            return True
        return self.path(name) is not None

    @cache
    def parse(self, path: Path) -> ast.Module:
        return ast.parse(path.read_bytes(), filename=str(path))

    @cache
    def exports(self, name: str) -> Bindings:
        path = self.path(name)
        package = name if path and path.name == "__init__.py" else name.rpartition(".")[0]
        bindings = Bindings(package)
        if path and path.is_file():
            tree = self.parse(path)
            if name == "vllm.envs":
                # envs.py also has TYPE_CHECKING-only default declarations. A
                # declaration without the runtime reader would still crash.
                for node in tree.body:
                    if isinstance(node, ast.If) and dotted(node.test) in {
                        ("TYPE_CHECKING",),
                        ("typing", "TYPE_CHECKING"),
                    }:
                        for stmt in node.orelse:
                            bindings.visit(stmt)
                    else:
                        bindings.visit(node)
            else:
                bindings.visit(tree)
            if "__getattr__" in bindings.names:
                for attr, origin in bindings.lazy.items():
                    bindings.add(attr, origin)
        return bindings

    def resolve(
        self, module: str, attr: str, seen: frozenset[tuple[str, str]] = frozenset()
    ) -> tuple[bool, set[str]]:
        if module in GENERATED_EXPORTS and self.path(module) is None:
            found = attr in GENERATED_EXPORTS[module]
            if found:
                self.generated_refs.add(f"{module}.{attr}")
            return found, set()
        key = (module, attr)
        if key in seen:
            return False, set()
        seen = seen | {key}
        exports = self.exports(module)
        found = False
        child_modules: set[str] = set()
        for origin in exports.names.get(attr, ()):
            if not origin or not is_internal(origin[0]):
                found = True
            elif len(origin) == 1 and self.module(origin[0]):
                found = True
                child_modules.add(origin[0])
            elif len(origin) == 2:
                ok, children = self.resolve(*origin, seen)
                found |= ok
                child_modules.update(children)
        # Importing a package member may load a sibling .py or subpackage.
        child = f"{module}.{attr}"
        if self.module(child):
            found = True
            child_modules.add(child)
        if not found:
            for star in exports.star:
                ok, children = self.resolve(star, attr, seen)
                found |= ok
                child_modules.update(children)
        return found, child_modules


class Check(ast.NodeVisitor):
    def __init__(self, index: SourceIndex, path: Path):
        self.index = index
        self.path = path.relative_to(index.root)
        parts = self.path.with_suffix("").parts
        self.package = ".".join(parts[:-1])
        self.scopes: list[dict[str, set[tuple[str, ...]]]] = []
        self.errors: set[str] = set()
        self.checked = 0

    def check(self, node: ast.AST, name: str, ok: bool) -> None:
        self.checked += 1
        if not ok:
            self.errors.add(f"{self.path}:{node.lineno}: unresolved {name}")

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        module = import_base(node, self.package)
        if is_internal(module):
            self.check(node, module, self.index.module(module))
            for entry in node.names:
                if entry.name != "*":
                    found, _ = self.index.resolve(module, entry.name)
                    self.check(node, f"{module}.{entry.name}", found)

    def visit_Import(self, node: ast.Import) -> None:
        for entry in node.names:
            if is_internal(entry.name):
                self.check(node, entry.name, self.index.module(entry.name))

    def check_chain(self, node: ast.AST, parts: tuple[str, ...]) -> None:
        for scope in reversed(self.scopes):
            if parts[0] in scope:
                origins = scope[parts[0]]
                break
        else:
            return
        modules = set()
        for origin in origins:
            if origin and is_internal(origin[0]):
                if len(origin) == 1:
                    modules.add(origin[0])
                else:
                    modules.update(self.index.resolve(*origin)[1])
        for attr in parts[1:]:
            next_modules = set()
            for module in modules:
                found, children = self.index.resolve(module, attr)
                self.check(node, f"{module}.{attr}", found)
                next_modules.update(children)
            modules = next_modules

    def visit_Attribute(self, node: ast.Attribute) -> None:
        if isinstance(node.ctx, ast.Load) and (parts := dotted(node)):
            self.check_chain(node, parts)
        else:
            self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        if (
            isinstance(node.func, ast.Name)
            and node.func.id in {"getattr", "hasattr"}
            and len(node.args) >= 2
            and isinstance(attr := node.args[1], ast.Constant)
            and isinstance(attr.value, str)
            and (parts := dotted(node.args[0]))
        ):
            self.check_chain(node, (*parts, attr.value))
        self.generic_visit(node)

    def body(self, nodes: list[ast.stmt], local_names=()) -> None:
        bindings = Bindings(self.package)
        for name in local_names:
            bindings.add(name)
        for node in nodes:
            bindings.visit(node)
        self.scopes.append(bindings.names)
        for node in nodes:
            self.visit(node)
        self.scopes.pop()

    def visit_Module(self, node: ast.Module) -> None:
        self.body(node.body)

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        for decorator in node.decorator_list:
            self.visit(decorator)
        self.visit(node.args)
        if node.returns:
            self.visit(node.returns)
        args = node.args
        names = [arg.arg for arg in args.posonlyargs + args.args + args.kwonlyargs]
        names.extend(arg.arg for arg in (args.vararg, args.kwarg) if arg is not None)
        self.body(node.body, names)

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        for expr in [*node.decorator_list, *node.bases, *node.keywords]:
            self.visit(expr)
        self.body(node.body)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--overlays", action="store_true")
    parser.add_argument("root", type=Path)
    parser.add_argument("paths", nargs="*")
    args = parser.parse_args()
    root = args.root.resolve()
    if not (root / "vllm").is_dir():
        parser.error(f"missing vllm/ under {root}")
    patch_dir = Path(__file__).resolve().parents[1] / "patches"
    if not args.paths:
        args.paths = json.loads((patch_dir / "vllm/series.json").read_text())["reviewed_paths"]
    if args.overlays:
        for entry in json.loads((patch_dir / "overlays/series.json").read_text()):
            args.paths.extend(entry["files"])
    index = SourceIndex(root)
    errors = []
    total = 0
    for rel in sorted(set(args.paths)):
        path = root / rel
        check = Check(index, path)
        check.visit(index.parse(path))
        errors.extend(sorted(check.errors))
        total += check.checked
    for error in errors:
        print(error, file=sys.stderr)
    if index.generated_refs:
        print("Generated symbols:", ", ".join(sorted(index.generated_refs)))
    print(f"Checked {total} source references in {len(set(args.paths))} files")
    return bool(errors)


if __name__ == "__main__":
    sys.exit(main())
